def num_stream():
    for x in range(1, 21):
        yield x


def even_filter(numbers):
    for num in numbers: 
        if num % 2 == 0:
            yield num


def squared_stream(numbers):
    for num in numbers: 
        yield num**2


# --- PIPELINE CHAINING ---
stream = num_stream()
evens = even_filter(stream)
results = squared_stream(evens)

for val in results:
    print(val)

